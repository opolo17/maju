/**
 * @param {Record<string, unknown>} obj
 * @param {string} path
 */
export function getNestedCopy(obj, path) {
  return path.split('.').reduce((acc, key) => {
    if (acc == null || typeof acc !== 'object') return undefined;
    return /** @type {Record<string, unknown>} */ (acc)[key];
  }, /** @type {unknown} */ (obj));
}

/**
 * @param {Locale} locale
 * @param {string} key
 * @param {Record<string, string | number>} [vars]
 */
export function translate(locale, key, vars = {}) {
  const copy = COPY[locale] ?? COPY[DEFAULT_LOCALE];
  let value = getNestedCopy(copy, key);
  if (value == null) {
    value = getNestedCopy(COPY[DEFAULT_LOCALE], key);
  }
  if (typeof value !== 'string') return key;
  return Object.entries(vars).reduce(
    (str, [name, val]) => str.replaceAll(`{${name}}`, String(val)),
    value,
  );
}
